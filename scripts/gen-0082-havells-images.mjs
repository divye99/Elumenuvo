// Generate supabase/migrations/0082_havells-image-galleries.sql from
// /tmp/hav-images.json (SKU-verified havells.com galleries) + the review
// list of products still under 3 photos (scripts/data/photos-review-list.txt).
//
// Only products that gained a 2nd+ photo get an update; single-image
// products keep images NULL (the PDP falls back to image_url) so the
// migration stays small and reversible.
import { readFile, writeFile } from "node:fs/promises";

const data = JSON.parse(await readFile("/tmp/hav-images.json", "utf8"));
const esc = (s) => s.replace(/'/g, "''");

const updates = [];
const review = [];
for (const p of data) {
  if (p.images.length >= 2) {
    updates.push(`update public.products set images = '${esc(JSON.stringify(p.images))}'::jsonb where id = '${p.id}';`);
  }
  if (p.images.length < 3) {
    review.push(`${p.id} | ${p.sku} | ${p.images.length} photo${p.images.length === 1 ? "" : "s"} | ${p.name}`);
  }
}

const sql = `-- 0082: Havells photo galleries - ordered image arrays scraped from
-- havells.com media_gallery, SKU-verified (a product only receives images
-- from the Magento item matching its own brand_sku, or that child's direct
-- configurable parent). ${updates.length} products gain a gallery; products
-- still on one photo keep images NULL and are listed for manual review in
-- scripts/data/photos-review-list.txt. Run AFTER 0081.
-- Generated by scripts/gen-0082-havells-images.mjs.

${updates.join("\n")}
`;
await writeFile("supabase/migrations/0082_havells-image-galleries.sql", sql);
await writeFile(
  "scripts/data/photos-review-list.txt",
  [
    `# Products still under 3 photos after the Havells crawl (${new Date().toISOString().slice(0, 10)})`,
    `# Sources tried: havells.com media_gallery (child + configurable parent).`,
    `# Non-Havells brands are a separate upcoming pass and are not listed here.`,
    "",
    ...review,
  ].join("\n")
);
const c = (n) => data.filter((p) => p.images.length === n).length;
console.log(`0082 written: ${updates.length} gallery updates · review list: ${review.length} rows (3+: ${data.length - review.length}, 2: ${c(2)}, 1: ${c(1)})`);
