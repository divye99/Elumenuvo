-- 0066: exact Havells competitor mappings.
--
-- Havells runs Magento. A "configurable" product (e.g. Inverter LED Bulb) is a
-- PARENT record whose variants (20 W, 30 W) are CHILD records, and the price
-- sits on the child. Magento will not return a child from a sku lookup - it is
-- reachable only inside its parent - so every child-SKU mapping silently
-- returned nothing and those products were never price-matched.
--
-- The match itself was always right: our brand_sku IS the Havells child SKU.
-- What was missing is the ADDRESS. competitor_code is stored as PARENT::CHILD
-- for children, and as the plain SKU for simple products.
--
-- Also corrects 9 products whose stored brand_sku was a PARENT sku (8 house
-- wires + the Ventilair exhaust fan). A parent quotes its CHEAPEST variant, so
-- those were tracking the wrong figure: the wires would have followed the 90 m
-- coil even if we later list 180 m, and the fan parent quotes the 230 mm while
-- its named child is the 300 mm. Each is now pinned to the exact variant.
--
-- Built from a full crawl of havells.com (138 categories, 2,054 products,
-- 1,484 child SKUs), so every code is verified against their live catalogue.
-- ═══════════════════════════════════════════════════════════════

